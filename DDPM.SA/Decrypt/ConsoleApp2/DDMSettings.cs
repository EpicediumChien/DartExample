    public class EARect
    {
        public double x { get; set; }
        public double y { get; set; }
        public double w { get; set; }
        public double h { get; set; }
        public double area { get; }

        public EARect(double X, double Y, double W, double H)
        {
            x = X;
            y = Y;
            w = W;
            h = H;
            area = W * H;
        }
    }

    public class CustLayout
    {
        public int ID { get; set; }
        public string Name { get; set; }
        public bool Overlap { get; set; }
        public List<EARect> Rects { get; set; }

        public CustLayout(int id, string name, bool overlap, List<EARect> rects)
        {
            ID = id;
            Name = name;
            Overlap = overlap;
            Rects = (rects == null ? new List<EARect>() : rects.ConvertAll(rect => new EARect(rect.x, rect.y, rect.w, rect.h)));
        }
    }

